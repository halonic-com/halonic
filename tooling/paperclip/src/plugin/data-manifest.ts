import { writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";

/**
 * The manifest file a plugin build ships: one JSON literal, exported as `manifest` and as the default export, with no
 * code. The server's plugin deployer can then read the manifest as data, without running a module that a build or a
 * changed dependency could make print something else (security review of halonic-com/server#80, HAL-19231). Paperclip
 * imports the same file and gets the same object.
 *
 * Throws when the manifest isn't plain JSON data (a function, `undefined`, a Date, a Map…), because those would be
 * lost or changed on the way.
 */
export function dataManifestSource(manifest: unknown): string {
  refuseProtoKeys(manifest, "manifest");
  const json = JSON.stringify(manifest, null, 2);
  if (json === undefined || !isDeepStrictEqual(JSON.parse(json), manifest)) {
    throw new Error(
      "the plugin manifest is not plain JSON data, so it can't be shipped as a data-only file",
    );
  }
  return `// Generated by the plugin build: data only, no code (HAL-19231).\nexport const manifest = ${json};\nexport default manifest;\n`;
}

/**
 * Refuses a `__proto__` key at any depth. `JSON.parse` makes it an own property, which is harmless on its own, but
 * code that copies the object key by key with assignment or `Object.assign` (as a reader of the manifest may) sets the
 * copy's prototype instead of a key; an object spread copies it as a plain key (Julian's review, HAL-19360).
 */
function refuseProtoKeys(value: unknown, where: string): void {
  if (value === null || typeof value !== "object") {
    return;
  }
  for (const key of Object.keys(value)) {
    if (key === "__proto__") {
      throw new Error(`the plugin manifest has a __proto__ key at ${where}`);
    }
    refuseProtoKeys((value as Record<string, unknown>)[key], `${where}.${key}`);
  }
}

/** Writes {@link dataManifestSource} over the bundled manifest. */
export async function writeDataManifest(file: string, manifest: unknown): Promise<void> {
  await writeFile(file, dataManifestSource(manifest));
}
