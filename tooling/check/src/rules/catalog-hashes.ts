import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { CheckContext } from "../lib/context.ts";
import { folderNamePattern } from "../lib/layout.ts";
import { Report } from "../lib/problems.ts";
import { catalogSourceHash, type ReadSource } from "./catalog-source-hash.ts";

// A package declares `"halonic": { "catalog": { "export": "definition" } }` to
// have every `src/<group>/<name>.ts` found without a hand-edited list. The
// list, with each entry's source hash (catalog-source-hash.ts), is a committed file, so a reviewer sees
// every added or changed entry in the diff and the shell's build can read the
// hashes (steppers architecture note on HAL-17491, 1.2 and 4.2). Plain
// `pnpm discover` never writes it: CI would rewrite a stale copy before this
// rule reads it. `pnpm discover --fix` does.

/** A package whose `src/<group>/<name>.ts` files are discovered and hashed. */
export interface HashedCatalog {
  /** The package folder, relative to the repo root. */
  readonly packageDirectory: string;
  /** The name each entry file exports, such as `definition`. */
  readonly exportName: string;
}

/** One discovered file: `github/upload-social-preview` for `src/github/upload-social-preview.ts`. */
export interface CatalogEntry {
  readonly key: string;
  /** Relative to the repo root. */
  readonly file: string;
}

/** The committed generated file of a hashed catalog, relative to the package. */
export const catalogFile = "src/catalog.generated.ts";

const rule = "catalog-hashes";
const exportNamePattern = /^[a-z][A-Za-z0-9]*$/;
// `<group>/<name>.ts` only: a test, fixture or other dotted file isn't an entry.
const entryPattern = /^([^/]+)\/([^/.]+)\.ts$/;

/** Reads every package's catalog declaration, reporting the ones declared wrong. */
export function readHashedCatalogs(context: CheckContext): {
  catalogs: HashedCatalog[];
  report: Report;
} {
  const report = new Report(rule);
  const catalogs: HashedCatalog[] = [];
  for (const pkg of context.packages) {
    const declared = (pkg.manifest.halonic as { catalog?: unknown } | undefined)?.catalog;
    if (declared === undefined) continue;
    const exportName = (declared as { export?: unknown } | null)?.export;
    if (typeof exportName !== "string" || !exportNamePattern.test(exportName)) {
      report.error(pkg.manifestPath, `halonic.catalog must be { "export": "<name>" }.`);
      continue;
    }
    catalogs.push({ packageDirectory: pkg.directory, exportName });
  }
  return { catalogs, report };
}

/** The catalog's entry files, sorted by key, and a problem for each badly named one. */
export function catalogEntries(
  context: CheckContext,
  catalog: HashedCatalog,
  report: Report,
): CatalogEntry[] {
  const prefix = `${catalog.packageDirectory}/src/`;
  const entries: CatalogEntry[] = [];
  for (const file of context.files) {
    if (!file.startsWith(prefix)) continue;
    const match = entryPattern.exec(file.slice(prefix.length));
    if (match === null) continue;
    const [, group = "", name = ""] = match;
    if (group === "generated") continue;
    if (!folderNamePattern.test(group) || !folderNamePattern.test(name)) {
      report.error(file, "Name the folder and the file in lowercase words joined by hyphens.");
      continue;
    }
    entries.push({ key: `${group}/${name}`, file });
  }
  return entries.sort((left, right) => left.key.localeCompare(right.key));
}

function variableName(key: string): string {
  return key.replace(/[/-]([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

/** The text the catalog's committed file must hold for these entries. */
export function renderCatalogFile(
  catalog: HashedCatalog,
  entries: readonly CatalogEntry[],
  readFile: ReadSource,
): string {
  const lines = [
    "// Generated by tooling/discover from src/<group>/<name>.ts. Do not edit; run pnpm discover --fix.",
    "",
  ];
  const properties: string[] = [];
  for (const entry of entries) {
    const variable = variableName(entry.key);
    const sourceHash = catalogSourceHash(catalog.packageDirectory, entry.file, readFile);
    lines.push(`import { ${catalog.exportName} as ${variable} } from "./${entry.key}.ts";`);
    properties.push(
      `  "${entry.key}": {`,
      `    ${catalog.exportName}: ${variable},`,
      `    sourceHash: "${sourceHash}",`,
      "  },",
    );
  }
  // Shaped as the formatter would write it, so the linter passes the file as generated.
  if (entries.length > 0) lines.push("");
  lines.push(
    "/** Every `src/<group>/<name>.ts`, by `<group>/<name>`, with the SHA-256 of its source and its imports. */",
  );
  if (properties.length === 0) {
    lines.push("export const catalogEntries = {} as const;");
  } else {
    lines.push("export const catalogEntries = {", ...properties, "} as const;");
  }
  return `${lines.join("\n")}\n`;
}

/** The expected text of a catalog's committed file, read from the checked tree. */
export function expectedCatalogFile(
  context: CheckContext,
  catalog: HashedCatalog,
  report: Report,
): string {
  const entries = catalogEntries(context, catalog, report);
  return renderCatalogFile(catalog, entries, (file) => readFileSync(join(context.root, file)));
}

/**
 * Each hashed catalog's committed file must list exactly its entry files,
 * each with the SHA-256 of its current source and the files it imports.
 */
export function checkCatalogHashes(context: CheckContext): Report {
  const { catalogs, report } = readHashedCatalogs(context);
  for (const catalog of catalogs) {
    const file = `${catalog.packageDirectory}/${catalogFile}`;
    const expected = expectedCatalogFile(context, catalog, report);
    const actual = context.files.includes(file) ? context.read(file) : undefined;
    if (actual !== expected) {
      report.error(
        file,
        `Out of date: it must list every src/<group>/<name>.ts with its source hash. Run "pnpm discover --fix" and commit it.`,
      );
    }
  }
  return report;
}
