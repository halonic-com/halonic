import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** Where the CLI app lives. */
export const cliAppDirectory = "apps/cli";

/** The CLI's commands: one folder each, holding a `command.ts`. */
export const cliCommandsDirectory = `${cliAppDirectory}/src/commands`;

/** Where the generated command list goes. It is gitignored. */
export const generatedCommandsFile = `${cliAppDirectory}/src/generated/commands.ts`;

/** `schema` → `schemaCommand`, `run-tests` → `runTestsCommand`: the export each command file names. */
export function commandExportName(folder: string): string {
  const camel = folder.replace(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
  return `${camel}Command`;
}

/** The command folders that hold a `command.ts`, sorted, so the list is the same on every machine. */
export function listCommandFolders(root: string): string[] {
  const directory = join(root, cliCommandsDirectory);
  if (!existsSync(directory)) {
    return [];
  }
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((folder) => existsSync(join(directory, folder, "command.ts")))
    .sort();
}

/** The text of the generated `commands.ts` for these command folders. */
export function renderCommandsFile(folders: readonly string[]): string {
  const lines = [
    "// Generated by tooling/discover from apps/cli/src/commands. Do not edit; run pnpm discover.",
    "",
    'import type { CliCommand } from "../command.ts";',
  ];
  for (const folder of folders) {
    lines.push(`import { ${commandExportName(folder)} } from "../commands/${folder}/command.ts";`);
  }
  const exports = folders.map(commandExportName).join(", ");
  lines.push(
    "",
    "/** Every CLI command, in folder order. The help lists them in this order too. */",
    `export const commands: readonly CliCommand[] = [${exports}];`,
  );
  return `${lines.join("\n")}\n`;
}

/** Writes the generated command list when the CLI app exists. Returns true if the file changed. */
export function writeCommandsFile(root: string): boolean {
  if (!existsSync(join(root, cliAppDirectory, "package.json"))) {
    return false;
  }
  const path = join(root, generatedCommandsFile);
  const text = renderCommandsFile(listCommandFolders(root));
  if (existsSync(path) && readFileSync(path, "utf8") === text) {
    return false;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  return true;
}
