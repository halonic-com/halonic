import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import {
  type CheckContext,
  folderNamePattern,
  type Problem,
  Report,
} from "@halonicjs/tooling-check";
import { type FolderDiscovery, generatedFolderFile } from "./folder-discovery.ts";

/** `task` → `task`, `sub-workflow` → `subWorkflow`. */
export function camelCase(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

/**
 * The subfolders of a discovery's folder, split into those that have its
 * file (the entries, sorted) and those that don't.
 */
export function discoveredFolders(
  context: CheckContext,
  discovery: FolderDiscovery,
): { entries: string[]; incomplete: string[] } {
  const prefix = `${discovery.packageDirectory}/${discovery.folder}/`;
  const subfolders = new Set<string>();
  const withFile = new Set<string>();
  for (const file of context.files) {
    if (!file.startsWith(prefix)) {
      continue;
    }
    const [subfolder, ...rest] = file.slice(prefix.length).split("/");
    if (subfolder === undefined || rest.length === 0) {
      continue;
    }
    subfolders.add(subfolder);
    if (rest.join("/") === discovery.file) {
      withFile.add(subfolder);
    }
  }
  const sorted = [...subfolders].sort();
  return {
    entries: sorted.filter((subfolder) => withFile.has(subfolder)),
    incomplete: sorted.filter((subfolder) => !withFile.has(subfolder)),
  };
}

/** Reports discovered subfolders without the discovery's file, or with a name that can't be an export. */
export function folderProblems(
  context: CheckContext,
  discoveries: readonly FolderDiscovery[],
): Problem[] {
  const report = new Report("discover");
  for (const discovery of discoveries) {
    const { entries, incomplete } = discoveredFolders(context, discovery);
    const folder = `${discovery.packageDirectory}/${discovery.folder}`;
    for (const subfolder of incomplete) {
      report.error(
        `${folder}/${subfolder}`,
        `Every folder in ${discovery.folder} needs a ${discovery.file}. Add it, or move the folder out.`,
      );
    }
    for (const subfolder of entries.filter((entry) => !folderNamePattern.test(entry))) {
      report.error(
        `${folder}/${subfolder}`,
        `Name the folder in lowercase words joined by hyphens; it becomes the key "${subfolder}" in ${generatedFolderFile(discovery)}.`,
      );
    }
  }
  return report.problems;
}

/** The text of a discovery's generated file for these entries (subfolder names, sorted). */
export function renderFolderFile(discovery: FolderDiscovery, entries: readonly string[]): string {
  const fromGenerated = (path: string): string => posix.relative("src/generated", path);
  const lines = [
    `// Generated by tooling/discover from ${discovery.folder}. Do not edit; run pnpm discover.`,
    "",
  ];
  if (discovery.satisfies !== undefined) {
    const { type, from } = discovery.satisfies;
    lines.push(`import type { ${type} } from "${fromGenerated(from)}";`);
  }
  const properties: string[] = [];
  for (const entry of entries) {
    const exportName = `${camelCase(entry)}${discovery.suffix}`;
    const path = fromGenerated(`${discovery.folder}/${entry}/${discovery.file}`);
    lines.push(`import { ${exportName} } from "${path}";`);
    const key = entry.includes("-") ? JSON.stringify(entry) : entry;
    properties.push(`  ${key}: ${exportName},`);
  }
  const type = discovery.satisfies === undefined ? "" : ` satisfies ${discovery.satisfies.type}`;
  lines.push(
    "",
    `/** Every folder in ${discovery.folder} that has a ${discovery.file}, by folder name. */`,
    `export const ${camelCase(discovery.name)} = {`,
    ...properties,
    `} as const${type};`,
  );
  return `${lines.join("\n")}\n`;
}

/** Writes every discovery's generated file. Returns the files that changed. */
export function writeFolderFiles(
  context: CheckContext,
  discoveries: readonly FolderDiscovery[],
): string[] {
  const written: string[] = [];
  for (const discovery of discoveries) {
    const file = generatedFolderFile(discovery);
    const path = join(context.root, file);
    const text = renderFolderFile(discovery, discoveredFolders(context, discovery).entries);
    if (existsSync(path) && readFileSync(path, "utf8") === text) {
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    written.push(file);
  }
  return written;
}
