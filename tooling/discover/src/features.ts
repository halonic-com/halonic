import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  type CheckContext,
  featureNamePrefix,
  readFeatureList,
  studioAppDirectory,
} from "@halonicjs/tooling-check";

/** Where the generated feature list goes. It is gitignored. */
export const generatedFeaturesFile = `${studioAppDirectory}/src/generated/features.ts`;

/** `agents` → `agentsFeature`, `source-control` → `sourceControlFeature`: the export each feature names. */
export function featureExportName(folder: string): string {
  const camel = folder.replace(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
  return `${camel}Feature`;
}

/** The text of the generated `features.ts` for these feature package names. */
export function renderFeaturesFile(featureNames: readonly string[]): string {
  const lines = [
    "// Generated by tooling/discover from the feature packages. Do not edit; run pnpm discover.",
    "",
  ];
  const exports: string[] = [];
  for (const name of featureNames) {
    const exportName = featureExportName(name.slice(featureNamePrefix.length));
    lines.push(`import { ${exportName} } from "${name}";`);
    exports.push(exportName);
  }
  if (featureNames.length > 0) {
    lines.push("");
  }
  lines.push(
    "/** What the Studio reads from each feature until the shell's defineFeature() exists. */",
    "export interface GeneratedFeature {",
    "  readonly id: string;",
    "  readonly title: string;",
    "}",
    "",
    "/** Every Studio feature, in folder order. Menu order comes from each feature's own order. */",
    `export const features: readonly GeneratedFeature[] = [${exports.join(", ")}];`,
  );
  return `${lines.join("\n")}\n`;
}

/** Writes the generated feature list when the Studio app exists. Returns true if the file changed. */
export function writeFeaturesFile(context: CheckContext): boolean {
  if (!existsSync(join(context.root, studioAppDirectory, "package.json"))) {
    return false;
  }
  const { folders } = readFeatureList(context);
  const path = join(context.root, generatedFeaturesFile);
  const text = renderFeaturesFile(folders);
  if (existsSync(path) && readFileSync(path, "utf8") === text) {
    return false;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  return true;
}

/**
 * Rewrites the feature dependencies in `apps/studio/package.json` to match
 * the feature folders exactly. Other dependencies stay as they are.
 *
 * @returns true if the file changed
 */
export function fixFeatureList(context: CheckContext): boolean {
  const path = join(context.root, studioAppDirectory, "package.json");
  if (!existsSync(path)) {
    return false;
  }
  const original = readFileSync(path, "utf8");
  const manifest = JSON.parse(original) as { dependencies?: Record<string, string> };
  const { folders } = readFeatureList(context);
  const others = Object.entries(manifest.dependencies ?? {}).filter(
    ([name]) => !name.startsWith(featureNamePrefix),
  );
  const merged = [...others, ...folders.map((name): [string, string] => [name, "workspace:*"])];
  merged.sort(([left], [right]) => left.localeCompare(right));
  manifest.dependencies = Object.fromEntries(merged);
  const text = `${JSON.stringify(manifest, null, 2)}\n`;
  if (text === original) {
    return false;
  }
  writeFileSync(path, text);
  return true;
}
