/** A run log of acme run "r1" holding one event of every kind, `run.started` first. */
export function everyKindLog(): RunEvent[] {
  return Object.values(everyKind).map((body, index) => ({
    runId: "r1",
    seq: index + 1,
    at: `2026-11-26T10:00:${String(index).padStart(2, "0")}.000Z`,
    ...body,
  }));
}
