// Prints one of the two files of our pinned copy of the integration guide
// (HAL-18266): `update-integration-guide.sh` runs it twice with the guide on
// standard input. It imports nothing, because this package is core code,
// which may not use Node's modules; the shell script reads and writes the files.
//
//   node scripts/integration-guide-module.ts guide < integrations.md > guide.generated.ts
//   node scripts/integration-guide-module.ts source <commit> < integrations.md > source.ts

const [what, commit] = process.argv.slice(2);

const chunks: Uint8Array[] = [];
for await (const chunk of process.stdin) {
  chunks.push(chunk);
}
const bytes = new Uint8Array(await new Blob(chunks).arrayBuffer());
const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);

if (what === "guide") {
  process.stdout.write(guideModule(text));
} else if (what === "source" && commit !== undefined && /^[0-9a-f]{40}$/.test(commit)) {
  process.stdout.write(sourceModule(commit, await sha256(bytes)));
} else {
  throw new Error("Usage: integration-guide-module.ts guide | source <40-character commit>");
}

/** The guide as a template literal, so core code reads it without a file system or a bundler. */
function guideModule(guide: string): string {
  const literal = guide.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
  return `// Generated by packages/core/assistant/scripts/update-integration-guide.sh. Don't edit by hand.
//
// halonic-com/integrations docs/guides/integrations.md, at the commit in ./source.ts.

/** The integration guide, byte for byte as at its source commit. */
export const integrationGuideText = \`${literal}\`;
`;
}

function sourceModule(sourceCommit: string, digest: string): string {
  return `// Generated by packages/core/assistant/scripts/update-integration-guide.sh. Don't edit by hand.

/** Where the pinned integration guide comes from, and the SHA-256 of its text there. */
export const integrationGuideSource = {
  repository: "halonic-com/integrations",
  path: "docs/guides/integrations.md",
  commit: "${sourceCommit}",
  sha256: "${digest}",
} as const;
`;
}

async function sha256(data: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", data);
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
}
