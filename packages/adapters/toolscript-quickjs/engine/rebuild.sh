#!/usr/bin/env bash
# Rebuilds the QuickJS-ng engine in src/generated/engine from the pins in
# SOURCES.json, and nothing else: every input is checked against its sha256
# before it is used, and the compiler runs in the pinned emsdk image, pulled
# by digest, without network. CI runs this and fails when the result differs
# from the committed files by a single byte (the toolscript-engine job).
#
# Usage: engine/rebuild.sh [output folder]   (needs bash, curl, unzip, git, node, docker)
set -euo pipefail

engine=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
out=${1:-$engine/../src/generated/engine}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

pin() {
  node -e 'const pins = JSON.parse(require("node:fs").readFileSync(process.argv[1], "utf8"));
    const value = process.argv[2].split(".").reduce((at, key) => at?.[key], pins);
    if (typeof value !== "string" && typeof value !== "number") process.exit(1);
    console.log(value);' "$engine/SOURCES.json" "$1"
}

# 1. The committed upstream files are the pinned ones.
node -e 'const pins = JSON.parse(require("node:fs").readFileSync(process.argv[1], "utf8"));
  for (const [file, { sha256 }] of Object.entries(pins.files)) console.log(`${sha256}  ${file}`);' \
  "$engine/SOURCES.json" >"$work/files.sha256"
(cd "$engine" && sha256sum --check --strict --quiet "$work/files.sha256")

# 2. The quickjs-ng release, checked before it is unpacked.
curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \
  --output "$work/amalgam.zip" "$(pin quickjsNg.amalgam.url)"
echo "$(pin quickjsNg.amalgam.sha256)  $work/amalgam.zip" | sha256sum --check --strict
mkdir -p "$work/src/vendor/quickjs-ng" "$work/src/c"
unzip -q -j "$work/amalgam.zip" -d "$work/src/vendor/quickjs-ng"
echo "$(pin quickjsNg.tag)" >"$work/src/vendor/quickjs-ng/VERSION"

# 3. The two patches: the wrapper's own module detection, then ours.
(cd "$work/src/vendor/quickjs-ng" && git apply "$engine/upstream/module-detection.patch")
cp "$engine/upstream/interface.c" "$work/src/c/interface.c"
(cd "$work/src/c" && git apply "$engine/interface.patch")
cp "$engine/build.sh" "$engine/symbols.json" "$engine/upstream/pre-extension.js" \
  "$engine/upstream/pre-wasm-memory.js" "$engine/upstream/exported-runtime-methods.json" "$work/src/"

# 4. Compile in the pinned image. The sources sit at /src in every build, so
# no host path ends up in the output. Emscripten builds its LTO system
# libraries on first use, into folders of its cache the image doesn't ship
# (as the wrapper's own emcc.sh does); they are mounted from this build's
# work folder, so they start empty every time.
image=$(pin emsdk.image)
docker pull --quiet "$image" >/dev/null
cache=(--volume "$work/src:/src")
for folder in sysroot/lib/wasm32-emscripten/lto sysroot/lib/wasm32-emscripten/thinlto \
  sysroot/lib/wasm32-emscripten/pic symbol_lists; do
  mkdir -p "$work/cache/$folder"
  cache+=(--volume "$work/cache/$folder:/emsdk/upstream/emscripten/cache/$folder")
done
docker run --rm --network none --user "$(id -u):$(id -g)" \
  --env SOURCE_DATE_EPOCH=0 --env HOME=/tmp \
  --env MODULE_MEMORY_BYTES="$(pin build.moduleMemoryBytes)" --env STACK_BYTES="$(pin build.shadowStackBytes)" \
  "${cache[@]}" --workdir /src "$image" bash build.sh

# 5. The outputs, plus the runtime files that come with them.
mkdir -p "$out"
rm -f "$out"/*
cp "$work/src/out/quickjs.mjs" "$work/src/out/quickjs.wasm" "$out/"
cp "$engine/upstream/ffi.mjs" "$out/ffi.mjs"
cat >"$out/quickjs.d.mts" <<'EOF'
// Generated by engine/rebuild.sh. Never edit.
import type { QuickJSSyncVariant } from "quickjs-emscripten-core";

type Loader = Awaited<ReturnType<QuickJSSyncVariant["importModuleLoader"]>>;
declare const QuickJSRaw: Extract<Loader, (...args: never[]) => unknown>;
export default QuickJSRaw;
EOF
# The .wasm once more, as base64 in a module, so the isolate loads it the
# same way on every runtime (src/engine.ts).
printf 'export default "%s";\n' "$(base64 --wrap=0 "$out/quickjs.wasm")" >"$out/quickjs-wasm.mjs"
cat >"$out/quickjs-wasm.d.mts" <<'EOF'
// Generated by engine/rebuild.sh. Never edit.
declare const quickjsWasm: string;
export default quickjsWasm;
EOF
cat >"$out/ffi.d.mts" <<'EOF'
// Generated by engine/rebuild.sh. Never edit.
import type { QuickJSSyncVariant } from "quickjs-emscripten-core";

export declare const QuickJSFFI: Awaited<ReturnType<QuickJSSyncVariant["importFFI"]>>;
EOF
(cd "$out" && sha256sum ./*)
